import ConceptArticle, {
  ConceptSection,
  DefinitionBox,
  Formula,
  Note,
} from "../components/ConceptArticle";

export default function PrimeraMediacion() {
  return (
    <ConceptArticle
      title="Primera mediación"
      kicker="Concepto ontológico"
      description="Colapso: el acontecimiento constitutivo mediante el cual determinación y persistencia comparecen como ser/estar"
    >
      <ConceptSection id="definicion" title="Definición">
        <DefinitionBox>
          <p>
            <strong>Primera mediación:</strong> operación ontológica mediante la cual una determinación y
            una persistencia colapsan frente a la alteridad y comparecen como un ser/estar efectivo. No es
            un ente ni una sustancia, sino el acontecimiento constitutivo donde identidad/sesgo y
            pasión/voluntad aparecen como una existencia determinada.
          </p>
        </DefinitionBox>

        <Formula label="Estructura del ser/estar">
          <span>identidad/sesgo + pasión/voluntad + primera mediación</span>
        </Formula>

        <p>
          La primera mediación no precede temporalmente al ser/estar ni lo causa desde fuera. Es el momento
          mismo en que algo acontece como siendo.
        </p>
      </ConceptSection>

      <ConceptSection id="operacion" title="Mediación como operación">
        <p>
          La primera mediación no debe confundirse con aquello que media. No es una tercera cosa colocada
          entre dos entidades previamente constituidas ni una sustancia capaz de tomar identidad y voluntad
          para producir después un ser.
        </p>

        <p>
          La mediación es una operación. Su función no consiste en agregar propiedades a algo ya existente,
          sino en señalar el acontecimiento mediante el cual una determinación y una persistencia comparecen
          efectivamente.
        </p>

        <Note title="No es una etapa separable">
          <p>
            La primera mediación no puede aislarse como si primero existiera la mediación y después surgiera
            aquello que es. La mediación ocurre en el mismo acontecimiento en que algo aparece como siendo.
          </p>
        </Note>
      </ConceptSection>

      <ConceptSection id="colapso" title="Colapso">
        <p>
          El término <strong>colapso</strong> nombra el preciso momento de la primera mediación. No significa
          destrucción, caída, fractura ni pérdida de una totalidad anterior. El colapso es constitución.
        </p>

        <p>
          Una determinación distingue aquello que algo es. Una persistencia expresa la pulsión mediante la
          cual aquello determinado continúa siendo. Sin embargo, ninguna de ambas comparece como ser/estar
          hasta que acontece.
        </p>

        <Formula label="Función constitutiva">
          <span>determinación + persistencia + colapso → ser/estar efectivo</span>
        </Formula>

        <p>
          La fórmula es una representación funcional, no una cronología. El colapso corresponde al punto en
          que determinación y persistencia comparecen frente a la alteridad como algo que es.
        </p>
      </ConceptSection>

      <ConceptSection id="no-linealidad" title="La primera mediación no es lineal">
        <p>
          La relación entre identidad, pasión y primera mediación no describe una secuencia temporal. No
          ocurre primero la identidad, después la voluntad y finalmente el colapso. Tampoco ocurre primero
          el colapso para que después aparezcan identidad y persistencia.
        </p>

        <Formula label="Representación constitutiva">
          <span>ser/estar = identidad/sesgo + pasión/voluntad + primera mediación</span>
        </Formula>

        <p>
          El signo de suma no establece prioridad temporal. Expresa que aquello que comparece como ser/estar
          requiere determinación, persistencia y acontecimiento.
        </p>
      </ConceptSection>

      <ConceptSection id="identidad" title="Primera mediación e identidad/sesgo">
        <p>
          La identidad/sesgo corresponde a la determinación del ser. Responde por aquello que permite
          afirmar que algo es esto y no aquello.
        </p>

        <p>
          La primera mediación no crea la identidad ni decide qué debe ser algo. La identidad determina;
          la primera mediación constituye el momento en que esa determinación acontece.
        </p>

        <Formula label="Distinción">
          <span>identidad/sesgo → determinación ; primera mediación → acontecer</span>
        </Formula>
      </ConceptSection>

      <ConceptSection id="pasion-voluntad" title="Primera mediación y pasión/voluntad">
        <p>
          La pasión/voluntad corresponde a la persistencia del estar. Expresa la pulsión mediante la cual
          aquello que es continúa siendo mientras atraviesa acontecimientos, accidentes y transformaciones.
        </p>

        <p>
          La primera mediación tampoco produce esa persistencia. La voluntad no aparece después del colapso
          como una fuerza añadida. La mediación constituye el momento en que determinación y persistencia
          comparecen conjuntamente como ser/estar.
        </p>

        <Formula label="Constituyentes">
          <span>identidad/sesgo determina ; pasión/voluntad persiste ; primera mediación colapsa</span>
        </Formula>
      </ConceptSection>

      <ConceptSection id="alteridad" title="Frente a la alteridad">
        <p>
          La primera mediación ocurre frente a la alteridad. La expresión no convierte la alteridad en una
          sustancia adicional ni pretende desarrollar aquí una teoría completa de su funcionamiento. Señala
          únicamente que aquello que comparece como determinado lo hace frente a una diferencia.
        </p>

        <p>
          Ser algo implica no ser indistintamente todo lo demás. Persistir implica atravesar acontecimientos
          sin perder completamente la continuidad que permite seguir hablando de aquello que persiste.
        </p>
      </ConceptSection>

      <ConceptSection id="caos" title="Primera mediación y Caos">
        <p>
          La primera mediación no debe representarse como una etapa posterior al Caos dentro de una secuencia
          lineal. El Caos no es un estado cronológicamente anterior al ser: funciona como infinito de
          posibilidades y límite de toda determinación.
        </p>

        <Formula label="Advertencia">
          <span>Caos → primera mediación → ser es una simplificación, no una cronología</span>
        </Formula>

        <p>
          La primera mediación no toma algo almacenado dentro del Caos y lo convierte en ser. El Caos no es
          un depósito de entidades futuras. La mediación señala únicamente el colapso mediante el cual una
          determinación y una persistencia comparecen efectivamente.
        </p>
      </ConceptSection>

      <ConceptSection id="acontecer" title="Acontecer y ser">
        <p>
          Todo aquello que es requiere acontecer. Una emoción es cuando acontece. Un pensamiento es cuando
          acontece. Un acto es cuando acontece. Una institución es en cuanto su determinación y persistencia
          comparecen efectivamente.
        </p>

        <p>
          Incluso aquello que se imagina es, porque el acto de imaginar ya ha acontecido. La primera
          mediación no exige existencia material, espacial o externa: exige acontecimiento.
        </p>

        <Note title="Escala de predicación">
          <p>
            Afirmar que algo ha colapsado no significa afirmar que exista del mismo modo que cualquier otra
            cosa. Significa únicamente que ha comparecido bajo alguna determinación y puede, desde una escala
            pertinente, ser objeto de predicación.
          </p>
        </Note>
      </ConceptSection>

      <ConceptSection id="definicion-final" title="Definición final">
        <DefinitionBox>
          <p>
            <strong>
              La primera mediación es el colapso constitutivo mediante el cual identidad/sesgo y
              pasión/voluntad comparecen frente a la alteridad como un ser/estar efectivo. No constituye un
              ente, una sustancia ni una etapa temporal previa al ser, sino la operación misma del acontecer:
              el preciso momento en que una determinación y una persistencia son.
            </strong>
          </p>
        </DefinitionBox>

        <p>
          La primera mediación no determina qué es algo y no explica por qué persiste. Expresa el
          acontecimiento mediante el cual aquello determinado y persistente comparece efectivamente como
          siendo.
        </p>
      </ConceptSection>
    </ConceptArticle>
  );
}
